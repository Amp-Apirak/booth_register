#!/usr/bin/env node
// Generates src/app/theme-light.css — the light theme.
//
// The UI was designed dark with Tailwind classes such as `text-white`,
// `text-slate-300`, `bg-white/5`, `border-white/10`, `text-cyan-300`.
// Tailwind 4 resolves every color through a CSS variable (--color-slate-300 …),
// so the light theme re-points those variables instead of rewriting every class:
//   • white/black and neutral scales (slate, gray, …) are mirrored (100↔900, 300↔700 …)
//     → `text-white` becomes near-black ink, `bg-white/5` a faint gray wash
//   • accent scales keep 500–700 (solid buttons) and map the light tints used as
//     text on dark (50–400) to the dark steps that read on white (400/300 → 700 …)
//   • `.theme-fixed` restores the original palette for things that must not flip
//     (white QR-code cards, the camera viewfinder).
// Run after upgrading Tailwind:  node scripts/gen-theme-light.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const themeCss = readFileSync(join(here, '../node_modules/tailwindcss/theme.css'), 'utf8');

const palette = {}; // family -> { shade -> value }
for (const [, family, shade, value] of themeCss.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) {
  (palette[family] ??= {})[shade] = value.trim();
}
const NEUTRAL = new Set(['slate', 'gray', 'zinc', 'neutral', 'stone', 'mauve', 'olive', 'mist', 'taupe']);
const MIRROR = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 400, 700: 300, 800: 200, 900: 100, 950: 50 };
const ACCENT = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 700, 500: 500, 600: 600, 700: 700, 800: 200, 900: 100, 950: 50 };

// Page surfaces used as `bg-surface*` (see @theme in globals.css)
const SURFACES_DARK = { surface: '#060913', 'surface-2': '#090d16', 'surface-3': '#0b1120', 'surface-4': '#0b1a1f', 'surface-5': '#080b18' };
const SURFACES_LIGHT = { surface: '#ffffff', 'surface-2': '#f8fafc', 'surface-3': '#f1f5f9', 'surface-4': '#ecf7f8', 'surface-5': '#f5f3ff' };

const light = [];
const fixed = [];
light.push(`  --color-white: ${palette.slate['900']};`);
light.push(`  --color-black: ${palette.slate['500']};`);
fixed.push('  --color-white: #fff;', '  --color-black: #000;');
for (const [family, shades] of Object.entries(palette)) {
  const map = NEUTRAL.has(family) ? MIRROR : ACCENT;
  for (const shade of Object.keys(shades)) {
    const target = shades[String(map[shade])] ?? shades[shade];
    light.push(`  --color-${family}-${shade}: ${target};`);
    fixed.push(`  --color-${family}-${shade}: ${shades[shade]};`);
  }
}
for (const [name, value] of Object.entries(SURFACES_LIGHT)) light.push(`  --color-${name}: ${value};`);
for (const [name, value] of Object.entries(SURFACES_DARK)) fixed.push(`  --color-${name}: ${value};`);

const out = `/* GENERATED by scripts/gen-theme-light.mjs from tailwindcss/theme.css — do not edit by hand. */
/* Hand-written light-theme rules (glass panels, gradients…) live in globals.css. */
:root[data-theme="light"] {
${light.join('\n')}
}

/* Keep the original (dark-design) palette inside these subtrees in any theme */
:root[data-theme="light"] .theme-fixed {
${fixed.join('\n')}
}
`;
writeFileSync(join(here, '../src/app/theme-light.css'), out);
console.log(`theme-light.css: ${light.length} light vars, ${fixed.length} fixed vars, ${Object.keys(palette).length} color families`);
